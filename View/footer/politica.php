<h1>Política de Privacidade – DoceMix</h1>
<p>A DoceMix respeita a privacidade de seus usuários e trata dados pessoais com transparência e segurança. Esta política descreve como coletamos, utilizamos e protegemos suas informações.</p>

<h2>1. Coleta de Dados</h2>
<p>Coletamos dados fornecidos pelo usuário (nome, e-mail, endereço, telefone, CPF para nota fiscal) e dados de navegação (IP, cookies e interações no site).</p>

<h2>2. Uso das Informações</h2>
<p>Os dados são utilizados para processar pedidos, realizar entregas, emitir documentos fiscais, melhorar a navegação e garantir segurança contra fraudes.</p>

<h2>3. Compartilhamento</h2>
<p>O compartilhamento ocorre apenas com serviços de pagamento, logística e obrigações legais. Não vendemos dados pessoais.</p>

<h2>4. Segurança</h2>
<p>Aplicamos medidas técnicas e administrativas para proteger suas informações contra acessos não autorizados.</p>

<h2>5. Direitos do Usuário</h2>
<p>O usuário pode solicitar acesso, correção ou exclusão dos dados por meio do e-mail: contato@docemix.com.</p>

<h2>6. Atualizações</h2>
<p>Esta política pode ser atualizada a qualquer momento. A versão vigente estará sempre disponível no site.</p>
<h2>7. Contato</h2>
<p>Para dúvidas ou solicitações relacionadas à privacidade, entre em contato pelo e-mail: contato@docemix.com.</p>
