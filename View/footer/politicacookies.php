<h1>Política de Cookies – DoceMix</h1>
<p>Utilizamos cookies para aprimorar a experiência do usuário, analisar o desempenho do site e personalizar funcionalidades.</p>

<h2>1. O que são Cookies</h2>
<p>Cookies são pequenos arquivos armazenados no navegador, responsáveis por lembrar preferências e melhorar o uso da plataforma.</p>

<h2>2. Tipos Utilizados</h2>
<ul>
    <li><strong>Essenciais:</strong> necessários para funcionamento do site.</li>
    <li><strong>Desempenho:</strong> analisam uso e melhorias.</li>
    <li><strong>Funcionais:</strong> registram preferências.</li>
    <li><strong>Marketing:</strong> exibem anúncios relevantes.</li>
</ul>

<h2>3. Gerenciamento</h2>
<p>O usuário pode desativar cookies pelo navegador, podendo comprometer algumas funcionalidades.</p>

<h2>4. Atualizações</h2>
<p>Esta política pode ser alterada a qualquer momento. A versão atual permanecerá publicada aqui.</p>
